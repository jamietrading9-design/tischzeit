create or replace function public.tisch_finance_totals(p_event_id bigint)
returns table (paid_sales_cents bigint, manual_income_cents bigint, expenses_cents bigint)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select
    coalesce((
      select sum(orders.total_cents + orders.tip_cents)
      from public.tisch_orders orders
      where orders.event_id = p_event_id
        and orders.status = 'paid'
        and orders.canceled_at is null
    ), 0),
    coalesce((
      select sum(entries.amount_cents)
      from public.tisch_finance_entries entries
      where entries.event_id = p_event_id and entries.kind = 'income'
    ), 0),
    coalesce((
      select sum(entries.amount_cents)
      from public.tisch_finance_entries entries
      where entries.event_id = p_event_id and entries.kind = 'expense'
    ), 0);
$$;

revoke all on function public.tisch_finance_totals(bigint) from public, anon, authenticated;
grant execute on function public.tisch_finance_totals(bigint) to service_role;

create or replace function public.tisch_reject_banned_customer_order()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  customer_is_banned boolean;
begin
  if new.customer_id is null then
    return new;
  end if;

  select banned into customer_is_banned
  from public.tisch_customers
  where id = new.customer_id
  for update;

  if not found or customer_is_banned then
    raise exception 'Bestellungen sind für dieses Gerät nicht möglich.' using errcode = '42501';
  end if;
  return new;
end;
$$;

drop trigger if exists tisch_orders_reject_banned_customer on public.tisch_orders;
create trigger tisch_orders_reject_banned_customer
before insert on public.tisch_orders
for each row execute function public.tisch_reject_banned_customer_order();
