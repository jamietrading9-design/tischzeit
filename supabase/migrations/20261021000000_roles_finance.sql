create table if not exists public.tisch_finance_entries (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.tisch_events(id) on delete cascade,
  kind text not null check (kind in ('income', 'expense')),
  amount_cents integer not null check (amount_cents between 1 and 100000000),
  description text not null check (char_length(description) between 1 and 240),
  entry_date date not null default current_date,
  created_by text not null references public.tisch_staff_users(username),
  created_at timestamptz not null default now()
);

create index if not exists tisch_finance_entries_event_date_idx
  on public.tisch_finance_entries(event_id, entry_date desc, id desc);

