create extension if not exists pgcrypto with schema extensions;

create table if not exists public.tisch_events (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 80),
  slug text not null unique check (slug ~ '^[a-z0-9-]{3,64}$'),
  created_at timestamptz not null default now()
);

create table if not exists public.tisch_tables (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.tisch_events(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 40),
  active boolean not null default true,
  unique (event_id, name),
  unique (event_id, id)
);

create table if not exists public.tisch_products (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.tisch_events(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  description text not null default '' check (char_length(description) <= 240),
  category text not null default 'Speisen' check (char_length(category) between 1 and 40),
  price_cents integer not null check (price_cents between 0 and 100000),
  available boolean not null default true,
  unique (event_id, id)
);

create table if not exists public.tisch_orders (
  id uuid primary key default gen_random_uuid(),
  event_id bigint not null references public.tisch_events(id) on delete cascade,
  table_id bigint not null,
  status text not null default 'new' check (status in ('new', 'preparing', 'ready', 'paid')),
  total_cents integer not null check (total_cents between 0 and 1000000),
  tip_cents integer not null default 0 check (tip_cents between 0 and 100000),
  created_at timestamptz not null default now(),
  paid_at timestamptz,
  unique (event_id, id),
  foreign key (event_id, table_id) references public.tisch_tables(event_id, id)
);

create table if not exists public.tisch_order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.tisch_orders(id) on delete cascade,
  product_id bigint not null,
  product_name text not null,
  quantity integer not null check (quantity between 1 and 20),
  unit_price_cents integer not null check (unit_price_cents between 0 and 100000),
  note text not null default '' check (char_length(note) <= 160)
);

create index if not exists tisch_orders_event_status_created_idx
  on public.tisch_orders(event_id, status, created_at desc);
create index if not exists tisch_order_items_order_idx
  on public.tisch_order_items(order_id, id);

create table if not exists public.tisch_staff_sessions (
  token_hash text primary key,
  expires_at timestamptz not null
);

alter table public.tisch_events enable row level security;
alter table public.tisch_tables enable row level security;
alter table public.tisch_products enable row level security;
alter table public.tisch_orders enable row level security;
alter table public.tisch_order_items enable row level security;
alter table public.tisch_staff_sessions enable row level security;

grant all on table
  public.tisch_events,
  public.tisch_tables,
  public.tisch_products,
  public.tisch_orders,
  public.tisch_order_items,
  public.tisch_staff_sessions
to service_role;
grant usage, select on sequence
  public.tisch_events_id_seq,
  public.tisch_tables_id_seq,
  public.tisch_products_id_seq,
  public.tisch_order_items_id_seq
to service_role;

create or replace function public.tisch_create_event(p_name text, p_slug text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  created_event public.tisch_events;
begin
  insert into public.tisch_events (name, slug)
  values (btrim(p_name), p_slug)
  returning * into created_event;

  insert into public.tisch_tables (event_id, name)
  select created_event.id, 'Tisch ' || table_number
  from generate_series(1, 12) as table_series(table_number);

  insert into public.tisch_products (event_id, name, description, category, price_cents)
  values
    (created_event.id, 'Bratwurst im Weckle', 'Vom Grill mit Senf oder Ketchup', 'Vom Grill', 450),
    (created_event.id, 'Rote Wurst', 'Traditionell vom Grill', 'Vom Grill', 450),
    (created_event.id, 'Pommes', 'Knusprig, mit Ketchup oder Mayo', 'Beilagen', 350),
    (created_event.id, 'Vegetarischer Flammkuchen', 'Schmand, Zwiebeln, Käse', 'Vegetarisch', 850),
    (created_event.id, 'Bier 0,5 l', 'Pils vom Fass', 'Getränke', 400),
    (created_event.id, 'Apfelschorle 0,4 l', 'Regionaler Apfelsaft, spritzig', 'Getränke', 300);

  return to_jsonb(created_event);
end;
$$;

create or replace function public.tisch_place_order(p_event_slug text, p_table_id bigint, p_items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  selected_event public.tisch_events;
  selected_table public.tisch_tables;
  created_order public.tisch_orders;
  item_input jsonb;
  selected_product public.tisch_products;
  order_total integer := 0;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) not between 1 and 40 then
    raise exception 'Bitte prüfe deine Bestellung.' using errcode = '22023';
  end if;

  select * into selected_event
  from public.tisch_events
  where slug = p_event_slug;
  if not found then
    raise exception 'Diese Veranstaltung wurde nicht gefunden.' using errcode = 'P0002';
  end if;

  select * into selected_table
  from public.tisch_tables
  where id = p_table_id and event_id = selected_event.id and active;
  if not found then
    raise exception 'Dieser Tisch ist nicht verfügbar.' using errcode = '22023';
  end if;

  for item_input in select value from jsonb_array_elements(p_items)
  loop
    if (item_input->>'quantity') is null or (item_input->>'quantity') !~ '^[0-9]+$'
      or (item_input->>'quantity')::integer not between 1 and 20
      or (item_input->>'productId') is null or (item_input->>'productId') !~ '^[0-9]+$' then
      raise exception 'Bitte prüfe deine Bestellung.' using errcode = '22023';
    end if;

    select * into selected_product
    from public.tisch_products
    where id = (item_input->>'productId')::bigint
      and event_id = selected_event.id
      and available;
    if not found then
      raise exception 'Ein Produkt ist inzwischen nicht mehr verfügbar.' using errcode = '22023';
    end if;
    order_total := order_total + selected_product.price_cents * (item_input->>'quantity')::integer;
    if order_total > 1000000 then
      raise exception 'Die Bestellung ist zu groß. Bitte teile sie auf.' using errcode = '22023';
    end if;
  end loop;

  insert into public.tisch_orders (event_id, table_id, total_cents)
  values (selected_event.id, selected_table.id, order_total)
  returning * into created_order;

  for item_input in select value from jsonb_array_elements(p_items)
  loop
    select * into selected_product
    from public.tisch_products
    where id = (item_input->>'productId')::bigint
      and event_id = selected_event.id
      and available;
    if not found then
      raise exception 'Ein Produkt ist inzwischen nicht mehr verfügbar.' using errcode = '22023';
    end if;
    insert into public.tisch_order_items
      (order_id, product_id, product_name, quantity, unit_price_cents, note)
    values (
      created_order.id,
      selected_product.id,
      selected_product.name,
      (item_input->>'quantity')::integer,
      selected_product.price_cents,
      coalesce(item_input->>'note', '')
    );
  end loop;

  return jsonb_build_object(
    'id', created_order.id,
    'event_id', created_order.event_id,
    'table_id', created_order.table_id,
    'table_name', selected_table.name,
    'status', created_order.status,
    'total_cents', created_order.total_cents,
    'tip_cents', created_order.tip_cents,
    'created_at', to_char(created_order.created_at at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    'paid_at', created_order.paid_at,
    'items', (
      select coalesce(
        jsonb_agg(jsonb_build_object(
          'product_name', oi.product_name,
          'quantity', oi.quantity,
          'unit_price_cents', oi.unit_price_cents,
          'note', oi.note
        ) order by oi.id),
        '[]'::jsonb
      )
      from public.tisch_order_items oi
      where oi.order_id = created_order.id
    )
  );
end;
$$;

insert into public.tisch_events (name, slug)
values ('Feuerwehrfest', 'feuerwehrfest')
on conflict (slug) do nothing;

insert into public.tisch_tables (event_id, name)
select event_row.id, 'Tisch ' || table_number
from public.tisch_events as event_row
cross join generate_series(1, 12) as table_series(table_number)
where event_row.slug = 'feuerwehrfest'
on conflict (event_id, name) do nothing;

insert into public.tisch_products (event_id, name, description, category, price_cents)
select event_row.id, seed.name, seed.description, seed.category, seed.price_cents
from public.tisch_events as event_row
cross join (values
  ('Bratwurst im Weckle', 'Vom Grill mit Senf oder Ketchup', 'Vom Grill', 450),
  ('Rote Wurst', 'Traditionell vom Grill', 'Vom Grill', 450),
  ('Pommes', 'Knusprig, mit Ketchup oder Mayo', 'Beilagen', 350),
  ('Vegetarischer Flammkuchen', 'Schmand, Zwiebeln, Käse', 'Vegetarisch', 850),
  ('Bier 0,5 l', 'Pils vom Fass', 'Getränke', 400),
  ('Apfelschorle 0,4 l', 'Regionaler Apfelsaft, spritzig', 'Getränke', 300)
) as seed(name, description, category, price_cents)
where event_row.slug = 'feuerwehrfest'
  and not exists (
    select 1 from public.tisch_products as existing_product
    where existing_product.event_id = event_row.id
  );

