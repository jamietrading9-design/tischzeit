create table if not exists public.tisch_staff_users (
  username text primary key check (char_length(username) between 3 and 64),
  password_hash text not null,
  role text not null check (role in ('admin', 'staff')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.tisch_staff_sessions
  add column if not exists user_id text references public.tisch_staff_users(username);

alter table public.tisch_events
  add column if not exists welcome_text text not null default 'Artikel auswählen und Bestellung an die Küche senden.',
  add column if not exists accent_color text not null default '#963b35';

create table if not exists public.tisch_customers (
  id bigint generated by default as identity primary key,
  identifier_hash text not null unique check (identifier_hash ~ '^[a-f0-9]{64}$'),
  banned boolean not null default false,
  ban_reason text not null default '' check (char_length(ban_reason) <= 240),
  created_at timestamptz not null default now()
);

alter table public.tisch_orders
  add column if not exists customer_id bigint references public.tisch_customers(id),
  add column if not exists canceled_at timestamptz,
  add column if not exists cancellation_reason text,
  add column if not exists canceled_by text;

create index if not exists tisch_orders_customer_created_idx
  on public.tisch_orders(customer_id, created_at desc);

alter table public.tisch_staff_users enable row level security;
alter table public.tisch_customers enable row level security;

grant all on table public.tisch_staff_users, public.tisch_customers to service_role;
grant usage, select on sequence public.tisch_customers_id_seq to service_role;

drop function if exists public.tisch_place_order(text, bigint, jsonb);

create or replace function public.tisch_place_order(
  p_event_slug text,
  p_table_id bigint,
  p_items jsonb,
  p_customer_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  selected_event public.tisch_events;
  selected_table public.tisch_tables;
  selected_customer public.tisch_customers;
  created_order public.tisch_orders;
  item_input jsonb;
  selected_product public.tisch_products;
  order_total integer := 0;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) not between 1 and 40 then
    raise exception 'Bitte prüfe deine Bestellung.' using errcode = '22023';
  end if;

  select * into selected_customer
  from public.tisch_customers
  where id = p_customer_id;
  if not found then
    raise exception 'Die Kundenakte wurde nicht gefunden.' using errcode = '22023';
  end if;
  if selected_customer.banned then
    raise exception 'Bestellungen sind für dieses Gerät nicht möglich.' using errcode = '42501';
  end if;

  select * into selected_event
  from public.tisch_events
  where slug = p_event_slug;
  if not found then
    raise exception 'Diese Veranstaltung wurde nicht gefunden.' using errcode = 'P0002';
  end if;

  select * into selected_table
  from public.tisch_tables
  where id = p_table_id and event_id = selected_event.id and active;
  if not found then
    raise exception 'Dieser Tisch ist nicht verfügbar.' using errcode = '22023';
  end if;

  for item_input in select value from jsonb_array_elements(p_items)
  loop
    if (item_input->>'quantity') is null or (item_input->>'quantity') !~ '^[0-9]+$'
      or (item_input->>'quantity')::integer not between 1 and 20
      or (item_input->>'productId') is null or (item_input->>'productId') !~ '^[0-9]+$' then
      raise exception 'Bitte prüfe deine Bestellung.' using errcode = '22023';
    end if;

    select * into selected_product
    from public.tisch_products
    where id = (item_input->>'productId')::bigint
      and event_id = selected_event.id
      and available;
    if not found then
      raise exception 'Ein Produkt ist inzwischen nicht mehr verfügbar.' using errcode = '22023';
    end if;
    order_total := order_total + selected_product.price_cents * (item_input->>'quantity')::integer;
    if order_total > 1000000 then
      raise exception 'Die Bestellung ist zu groß. Bitte teile sie auf.' using errcode = '22023';
    end if;
  end loop;

  insert into public.tisch_orders (event_id, table_id, total_cents, customer_id)
  values (selected_event.id, selected_table.id, order_total, selected_customer.id)
  returning * into created_order;

  for item_input in select value from jsonb_array_elements(p_items)
  loop
    select * into selected_product
    from public.tisch_products
    where id = (item_input->>'productId')::bigint
      and event_id = selected_event.id
      and available;
    if not found then
      raise exception 'Ein Produkt ist inzwischen nicht mehr verfügbar.' using errcode = '22023';
    end if;
    insert into public.tisch_order_items
      (order_id, product_id, product_name, quantity, unit_price_cents, note)
    values (
      created_order.id,
      selected_product.id,
      selected_product.name,
      (item_input->>'quantity')::integer,
      selected_product.price_cents,
      coalesce(item_input->>'note', '')
    );
  end loop;

  return jsonb_build_object(
    'id', created_order.id,
    'event_id', created_order.event_id,
    'table_id', created_order.table_id,
    'table_name', selected_table.name,
    'status', created_order.status,
    'total_cents', created_order.total_cents,
    'tip_cents', created_order.tip_cents,
    'created_at', to_char(created_order.created_at at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    'paid_at', created_order.paid_at,
    'customer_id', created_order.customer_id,
    'canceled_at', created_order.canceled_at,
    'cancellation_reason', created_order.cancellation_reason,
    'canceled_by', created_order.canceled_by,
    'items', (
      select coalesce(
        jsonb_agg(jsonb_build_object(
          'product_name', oi.product_name,
          'quantity', oi.quantity,
          'unit_price_cents', oi.unit_price_cents,
          'note', oi.note
        ) order by oi.id),
        '[]'::jsonb
      )
      from public.tisch_order_items oi
      where oi.order_id = created_order.id
    )
  );
end;
$$;

revoke all on function public.tisch_place_order(text, bigint, jsonb, bigint) from public, anon, authenticated;
grant execute on function public.tisch_place_order(text, bigint, jsonb, bigint) to service_role;
